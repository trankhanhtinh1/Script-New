inline const ChampionEntry* FindEntry(SDK::ChampionId championId) {
    if (championId == SDK::ChampionId::Unknown) {
        return nullptr;
    }
    for (const auto& entry : AllChampions) {
        if (entry.Profile && entry.Profile->ChampionId == championId) {
            return &entry;
        }
    }
    return nullptr;
}

inline const ChampionProfile* Find(SDK::ChampionId championId) {
    const auto* entry = FindEntry(championId);
    return entry ? entry->Profile : nullptr;
}

inline bool Supports(SDK::ChampionId championId) {
    return Find(championId) != nullptr;
}

inline void Load(SDK::ChampionId championId) {
    if (const auto* entry = FindEntry(championId)) {
        Engine::OnGameLoad(*entry->Profile, entry->Controller);
    }
}

inline void Unload() {
    Engine::OnUnload();
}

